const BY_KEY = new Map(ICONS.map((i) => [i.key, i]))

export function iconByKey(key: string | undefined | null): IconDef | undefined {
  return key ? BY_KEY.get(key) : undefined
}

/**
 * أمسارٌ مُغلق؟ فذاك جسمُ الأيقونة يُصبَغ، وما سواه خطٌّ يُخطّ.
 *
 * **و`z` علامةُ الجسد لا علامةُ الإغلاق**: التفصيلُ المُطوَّق — كمعيَّن
 * المصحف — يُعاد إلى نقطة بدئه بالإحداثيّات ولا يُختم بـ`z`، فيبقى خطًّا ولا
 * يصير جسدًا ثانيًا يُصبَغ.
 */
const closed = (d: string) => /z\s*$/i.test(d)

/** الدائرةُ الصغيرة نقطةٌ تُملأ، والكبيرةُ جسمٌ يُصبَغ صبغًا خفيفًا */
const DOT_R = 1.6

/** شفافيّةُ الجسد المصبوغ. طبقةٌ واحدة لا لكلّ مسارٍ طبقة — انظر `Icon`. */
const BODY_ALPHA = 0.2

/**
 * سُمكُ خطّ الأيقونة يتبع حجمَها عكسًا، فيبقى ما **يراه الناظر** واحدًا.
 *
 * والرسمُ في مربّع ٢٤ يُصغَّر إلى الحجم المطلوب، فسُمكٌ ثابتٌ في المربّع
 * يُرى مختلفًا في الشاشة: ١٫٧ في أيقونةِ ١١ بكسلًا تصير على الشاشة ٠٫٨ من
 * البكسل — خيطًا دون البكسل الواحد يتقطّع في الرسم ويشحب، فتُرى الأيقونةُ
 * كأنها خُطَّت باليد لا كأنها رمزٌ مضبوط — وهي في أيقونةِ ٢٦ تصير ١٫٨
 * فتُرى ثخينةً مصمتة. فيُقسَم ثابتٌ على الحجم ليستوي المرئيُّ منها، ويُحدّ
 * طرفاه: لا ينعدم في الكبيرة ولا يمتلئ جوفُ الصغيرة.
 */
function strokeOf(size: number): number {
  return Math.min(2.9, Math.max(1.15, 33 / size))
}

/**
 * رسمُ الأيقونة بمفتاحها.
 *
 * وما لا رسمَ له يُرسم دائرةً منقوطة لا فراغًا: موضعُ الأيقونة يبقى محفوظًا
 * فلا تختلّ الصفوف، ويُعرف أنّ ثمّ رمزًا لم يُختر بعد.
 *
 * **والرسمُ نوبتان لا نوبةً واحدة**: تُصبَغ الأجسادُ كلُّها أوّلًا في طبقةٍ
 * واحدة، ثم تُخطّ الخطوطُ كلُّها فوقها. وكان كلُّ مسارٍ يُرسم بجسده وخطّه
 * معًا على ترتيبه في القائمة، فوقع من ذلك ما يُرى تداخلًا:
 *
 *   ١. **الجسدُ يغسل ما تحته**. دائرةُ «تحرير» تلي علامةَ الصحّ في قائمتها،
 *      فتُرسم بعدها فيقع صبغُها على العلامة فتشحب. وكذلك «تعقُّب» و«مسألة»
 *      و«نادرة» و«وقت» و«لؤلؤة» — وهي أنواعُ الفوائد المعروضة في كلّ بطاقة.
 *   ٢. **الصبغُ يتضاعف حيث تتداخل الأجساد**. جسدانِ بشفافيّة الخُمس يقع
 *      أحدُهما على الآخر فتصير البقعةُ خُمسين، فيُرى فيهما لطخةٌ داكنة لا
 *      معنى لها.
 *
 * فالطبقةُ الواحدة (`opacity` على المجموعة لا على كلّ مسار) تُسطَّح قبل أن
 * تُشفَّف، فلا يتضاعف المتداخلُ منها. والخطوطُ بعدها فلا يغسلها شيء.
 */
export function Icon(
  { name, size = 18, plain, placeholder, style }: {
    name?: string | null
    size?: number
    /**
     * تلبس لونَ موضعها لا لونَها: تُمرَّر في الرُّقعة المضغوطة وفي الشارة
     * المصمتة — أرضُهما لونُ المكتبة، فلونٌ ثانٍ فوقه مزاحمة.
     */
    plain?: boolean
    /**
     * يُرسم مكانَ ما لا أيقونةَ له دائرةٌ منقوطة. وهي في المُنتقي وحده —
     * موضعٌ شاغر يُنادي على من يملؤه — وأمّا في البطاقات فلا: بابٌ بلا رمزٍ
     * يُعرض باسمه، ودائرةٌ فارغة إلى جانبه ضجيجٌ لا خبر.
     */
    placeholder?: boolean
    style?: CSSProperties
  },
) {
  const def = iconByKey(name)
  if (!def && !placeholder) return null
  const color = plain || !def ? 'currentColor' : `var(--ic-${def.tone})`
  const props = {
    width: size,
    height: size,
    viewBox: '0 0 24 24',
    fill: 'none',
    stroke: color,
    strokeWidth: strokeOf(size),
    strokeLinecap: 'round' as const,
    strokeLinejoin: 'round' as const,
    'aria-hidden': true,
    style,
  }
  if (!def) {
    return (
      <svg {...props}>
        <circle cx="12" cy="12" r="7" strokeDasharray="2.5 3" />
      </svg>
    )
  }

  const circles = def.c ?? []
  const bodies = def.d.filter(closed)
  const rings = circles.filter(([, , r]) => r > DOT_R)
  const dots = circles.filter(([, , r]) => r <= DOT_R)

  return (
    <svg {...props}>
      {/* النوبةُ الأولى: الأجسادُ مصبوغةً في طبقةٍ واحدة تُشفَّف بعد
          تسطيحها، فلا يتضاعف اللونُ حيث يقع جسدٌ على جسد */}
      {(bodies.length > 0 || rings.length > 0) && (
        <g opacity={BODY_ALPHA} fill={color} stroke="none">
          {bodies.map((d, i) => <path key={i} d={d} />)}
          {rings.map(([cx, cy, r], i) => <circle key={i} cx={cx} cy={cy} r={r} />)}
        </g>
      )}

      {/* والثانيةُ: الخطوطُ كلُّها فوقها، فلا يغسل جسدٌ خطًّا */}
      {def.d.map((d, i) => <path key={i} d={d} fill="none" />)}
      {rings.map(([cx, cy, r], i) => (
        <circle key={`r${i}`} cx={cx} cy={cy} r={r} fill="none" />
      ))}

      {/* والنقطُ آخرًا: مملوءةٌ لا مصبوغة، وهي أدقُّ ما في الرسم فلا يعلوها شيء */}
      {dots.map(([cx, cy, r], i) => (
        <circle key={`d${i}`} cx={cx} cy={cy} r={r} fill={color} />
      ))}
    </svg>
  )
}
