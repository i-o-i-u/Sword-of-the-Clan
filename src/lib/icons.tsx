// كانت الأيقوناتُ قبلُ يجتهد كلٌّ منها لنفسه: هذه جسدٌ مصمت وتلك خطوطٌ محضة،
// وهذه تملأ المربّع وتلك تنزوي في وسطه، وهذه سبعةُ مسارٍ وتلك مسارانِ — فإذا
// اجتمعن في شبكةٍ واحدة رأيتَ رسومًا شتّى لا أسرةً واحدة. فقُيِّدت بخمسٍ:
//
//   ١. **لكلّ أيقونةٍ جسدٌ واحد مصبوغ** — مسارٌ مُغلق (منتهٍ بـ`z`) أو دائرةٌ
//      كبيرة — وما بقي خطوطٌ فوقه. فلا أيقونةَ خطوطٌ محضة، ولا أيقونةَ كتلةٌ
//      صمّاء. وهذا هو الذي وحَّد ثِقَلَها في الشبكة.
//
//   ٢. **والأجسادُ من معجمٍ معدود** (`PAGE` وما بعده): ما تشابه من الرموز
//      تشابه رسمًا لا تقديرًا — فكتبُ المكتبة كلُّها على جسد `BOOK` نفسه،
//      والقبابُ والمحاريبُ على `ARCH`، والأوعيةُ على `VESSEL`. ولو تُرك كلُّ
//      رسمٍ لاجتهاده لاختلفت الكتبُ في الشبكة الواحدة عرضًا واستدارةً.
//
//   ٣. **الرسمُ في ٢٠×٢٠ من المربّع ٢٤** (من ٢٫٥ إلى ٢١٫٥): حاشيةٌ لا يُخرَق
//      عنها، فلا تلتصق أيقونةٌ بحدّ موضعها وأختُها منزوية.
//
//   ٤. **خمسةُ مسارٍ لا أكثر** (جسدٌ وأربعةُ تفاصيل): الأيقونةُ تُعرض في أحدَ
//      عشرَ بكسلًا في رُقعة البطاقة، وما زاد على ذلك يلتبس فيها فيصير لطخة.
//
//   ٥. **الاستداراتُ من مقاديرَ معلومة**: زاويةُ اللوح ٢، ودائرةُ الجسد ٨٫٥
//      أو ٧٫٥، والنقطةُ ١٫٢. فلا تُقدَّر بالحدس.
//
// **والمُغلَق يُصبَغ، فالتفصيلُ المُطوَّق يُعاد إلى مبدئه ولا يُختم بـ`z`**:
// معيَّنُ المصحف مثلًا يُرسم بأضلاعه الأربعة راجعًا إلى نقطة بدئه، فيبقى خطًّا
// ولا يصير جسدًا ثانيًا. فـ`z` علامةُ الجسد لا علامةُ الإغلاق.
//
// ===========================================================================
//
// **وهي ملوَّنةٌ ثنائيّةُ الطبقة**: لكلّ أيقونةٍ لونُها من لوحةٍ ثمانيّة
// (`tone`)، يُصبَغ به جسمُها صبغًا خفيفًا ويُخطّ عليه حدُّها. واللونُ خبرٌ لا
// زينة: تُعرف الأبوابُ في الشبكة بألوانها قبل أن تُقرأ أسماؤها.
//
// **واللونُ يُرفع حيث يُزاحمه لون** (`plain`): الرُّقعةُ المضغوطة أرضُها لونُ
// المكتبة، فتُلبَس الأيقونةُ لونَ موضعها ولا تُقاتله.
//
// **وسُمكُ خطِّها يتبع حجمَها عكسًا** (`strokeOf`)، ليبقى ما يراه الناظرُ
// واحدًا: سُمكٌ ثابتٌ في المربّع يُرى خيطًا دون البكسل في أيقونةِ ١١، وثخينًا
// مصمتًا في أيقونةِ ٢٦ — فتُقرأ الأولى كأنها خُطَّت باليد لا كأنها رمزٌ
// مضبوط. **ورسمُها نوبتان لا نوبةً واحدة** (`Icon`): تُصبَغ الأجسادُ كلُّها
// أوّلًا في طبقةٍ واحدة، ثم تُخطّ الخطوطُ فوقها — فلا يغسل جسدٌ خطًّا تحته،
// ولا يتضاعف صبغٌ حيث يقع جسدٌ على جسد.
//
// ولا تُجلب من خارج: ملفٌ واحدٌ في الحزمة، لا نداءَ شبكةٍ ولا خطَّ أيقوناتٍ
// يُحمَّل.
//
// **والمفتاحُ (`key`) هو ما يُحفظ في القاعدة لا الرسمُ نفسه**: تُبدَّل الرسومُ
// وتُحسَّن ولا يتغيّر ما في المستندات — وقد بُدِّلت كلُّها مرّةً واحدة على هذا
// النظام، فلم يتغيّر في القاعدة حرف. ومفتاحٌ لا رسمَ له اليوم لا يكسر شيئًا:
// تسقط عنه `Icon` إلى دائرةٍ منقوطة، فيبقى موضعُها محفوظًا ولا تختلّ الصفوف.
//
// وهي مقسومةٌ أبوابًا (`group`) كي تُطلب من بابها في المُنتقي: مئةٌ وثمانون
// أيقونةً في شبكةٍ واحدة لا تُقرأ.

