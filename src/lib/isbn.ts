// الترقيم الدولي المعياريّ للكتاب (ردمك / ISBN).
//
// الرقم ثلاثَ عشرةَ خانةً في أربعة حقول: بادئةٌ عالميّة (978 أو 979)، فرقمُ
// مجموعة التسجيل — وهي البلد أو اللغة —، ثم رقمُ الناشر ورقمُ العنوان
// مجتمعَين، ثم خانةُ التحقُّق. ومواضعُ الشرطات ليست ثابتة: طولُ رقم المجموعة
// يُشتقّ من قيمته على جدولٍ في المعيار.
//
// **وحدُّ ما يُشرَّط هنا: البادئةُ والمجموعةُ وخانةُ التحقُّق.** أمّا الفصلُ
// بين رقم الناشر ورقم العنوان فيحتاج جدولَ نطاقاتٍ يتغيّر مع كل تسجيلٍ
// جديد، ولا تُحفظ منه نسخةٌ ميّتة في الشيفرة: شرطةٌ في غير موضعها أسوأُ من
// تركها. فيُكتب «978-603-012345-2» لا «978-603-01-2345-2».
//
// ولا يُنادى من هنا خادمٌ خارجيّ: ما يُعرف يُعرف من الرقم نفسه.

/** الأرقام العربية الهندية كما قد تُلصَق من نصّ */
const EASTERN = '٠١٢٣٤٥٦٧٨٩'

/**
 * ما يُعتدّ به من المكتوب: الأرقام وحدها، والحرف X في آخر الردمك العشاريّ
 * (وهو خانةُ تحقُّقٍ قيمتُها عشرة). وما سواهما — شرطاتٌ وفراغاتٌ وحروف —
 * يسقط، فيصحّ اللصقُ من أيّ صفحةٍ كانت.
 */
export function isbnDigits(raw: string): string {
  let out = ''
  for (const ch of raw) {
    const eastern = EASTERN.indexOf(ch)
    if (eastern !== -1) { out += String(eastern); continue }
    if (ch >= '0' && ch <= '9') { out += ch; continue }
    if ((ch === 'X' || ch === 'x') && out.length === 9) out += 'X'
  }
  return out.slice(0, 13)
}

