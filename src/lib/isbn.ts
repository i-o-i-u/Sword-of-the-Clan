/** حقولُ الرقم مفصولة: بادئةٌ (في الثلاثيِّ عشر وحده) فمجموعةٌ فمتنٌ فتحقُّق */
interface IsbnParts {
  prefix: string
  group: string
  body: string
  check: string
}

/**
 * يقسم ما كُتب على حقوله ولو كان ناقصًا: يُفصَل ما تبيّن ويُترك ما بعده،
 * فالتشريطُ يجري مع الكتابة حرفًا حرفًا لا بعد تمام الرقم.
 */
function split(digits: string): IsbnParts {
  const thirteen = digits.startsWith('978') || digits.startsWith('979')
  const prefix = thirteen ? digits.slice(0, 3) : ''
  const rest = digits.slice(prefix.length)

  const len = prefix === '979' ? groupLength979(rest) : groupLength978(rest)
  if (len === null) return { prefix, group: rest, body: '', check: '' }

  const group = rest.slice(0, len)
  const after = rest.slice(len)
  // خانةُ التحقُّق لا تُفصَل إلا إذا تمّ الرقم، وإلّا انفصل آخرُ ما كُتب عنه
  const full = thirteen ? digits.length === 13 : digits.length === 10
  return full
    ? { prefix, group, body: after.slice(0, -1), check: after.slice(-1) }
    : { prefix, group, body: after, check: '' }
}

/** الرقم مُشرَّطًا كما يُكتب ويُحفظ: «978-603-012345-2» */
export function formatIsbn(raw: string): string {
  const digits = isbnDigits(raw)
  if (!digits) return ''
  const { prefix, group, body, check } = split(digits)
  return [prefix, group, body, check].filter(Boolean).join('-')
}

/** حالُ ما كُتب: أتامٌّ هو أم ناقص، أصحيحٌ أم مُحرَّف */
export type IsbnState = 'فارغ' | 'ناقص' | 'صحيح' | 'خطأ'

export interface IsbnInfo {
  /** ما كُتب مجرَّدًا من الشرطات */
  digits: string
  state: IsbnState
  /** الرقم مُشرَّطًا */
  formatted: string
  /** بلدُ المجموعة أو لغتُها، إن عُرفت */
  country: string
  /** رقمُ المجموعة نفسه، وإن لم يُعرف اسمُها */
  group: string
  /** عشاريٌّ صحيح، ومقابلُه الثلاثيُّ عشر — يُعرض ليُؤخذ بضغطة */
  as13: string
  /** ما ينبغي أن تكون عليه خانةُ التحقُّق حين تخالف */
  expected: string
}

/**
 * وصفُ ما كُتب في حقل الردمك: تشريطُه، وحكمُ صحّته، وبلدُ مجموعته.
 *
 * ويُقبل العشاريُّ كما يُقبل الثلاثيُّ عشر: كتبٌ كثيرة طُبعت قبل ٢٠٠٧ لا
 * تحمل إلا إيّاه، فلا يُردّ على صاحبه، بل يُعرض له مقابلُه ليأخذه إن شاء.
 */
export function isbnInfo(raw: string): IsbnInfo {
  const digits = isbnDigits(raw)
  const parts = split(digits)
  const names = parts.prefix === '979' ? GROUP_NAMES_979 : GROUP_NAMES
  const base: IsbnInfo = {
    digits,
    state: 'فارغ',
    formatted: formatIsbn(digits),
    country: names[parts.group] ?? '',
    group: parts.group,
    as13: '',
    expected: '',
  }

  if (!digits) return base
  if (digits.length === 13) {
    const want = checkDigit13(digits.slice(0, 12))
    return { ...base, state: digits[12] === want ? 'صحيح' : 'خطأ', expected: want }
  }
  if (digits.length === 10) {
    const want = checkDigit10(digits.slice(0, 9))
    const ok = digits[9] === want
    return {
      ...base,
      state: ok ? 'صحيح' : 'خطأ',
      expected: want,
      as13: ok ? formatIsbn(toIsbn13(digits) ?? '') : '',
    }
  }
  return { ...base, state: 'ناقص' }
}
