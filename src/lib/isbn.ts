/** خانةُ التحقُّق في الردمك الثلاثيِّ عشر، من أوّل اثنتَي عشرةَ خانة */
export function checkDigit13(twelve: string): string {
  let sum = 0
  for (let i = 0; i < 12; i++) sum += Number(twelve[i]) * (i % 2 ? 3 : 1)
  return String((10 - (sum % 10)) % 10)
}

/** وخانتُه في العشاريّ، من أوّل تسع. وقد تبلغ عشرةً فتُكتب X */
export function checkDigit10(nine: string): string {
  let sum = 0
  for (let i = 0; i < 9; i++) sum += Number(nine[i]) * (10 - i)
  const rest = (11 - (sum % 11)) % 11
  return rest === 10 ? 'X' : String(rest)
}

/** الردمك العشاريُّ يُحوَّل إلى ثلاثيِّ عشر ببادئة 978 وخانةِ تحقُّقٍ جديدة */
export function toIsbn13(digits: string): string | null {
  if (digits.length !== 10) return null
  const twelve = '978' + digits.slice(0, 9)
  return twelve + checkDigit13(twelve)
}

