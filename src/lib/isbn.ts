/** ومجموعات البادئة 979 قليلةٌ معدودة */
const GROUP_NAMES_979: Record<string, string> = {
  '8': 'الولايات المتّحدة', '10': 'فرنسا', '11': 'كوريا', '12': 'إيطاليا',
}

