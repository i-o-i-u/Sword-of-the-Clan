/**
 * طولُ رقم المجموعة تحت البادئة 978. القاعدة ثابتةٌ في المعيار:
 * ٠-٥ و٧ خانةٌ واحدة، و٦٠٠-٦٤٩ ثلاث، و٨٠-٩٤ خانتان، و٩٥٠-٩٨٩ ثلاث،
 * و٩٩٠٠-٩٩٨٩ أربع، و٩٩٩٠٠-٩٩٩٩٩ خمس.
 */
function groupLength978(body: string): number | null {
  const n = (len: number) => Number(body.slice(0, len))
  const d1 = body[0]
  if (d1 === undefined) return null
  if ('012345'.includes(d1) || d1 === '7') return 1
  if (d1 === '6') {
    if (body.length < 3) return null
    return n(3) >= 600 && n(3) <= 649 ? 3 : null
  }
  if (body.length < 2) return null
  if (n(2) >= 80 && n(2) <= 94) return 2
  if (body.length < 3) return null
  if (n(3) >= 950 && n(3) <= 989) return 3
  if (body.length < 4) return null
  if (n(4) >= 9900 && n(4) <= 9989) return 4
  if (body.length < 5) return null
  if (n(5) >= 99900 && n(5) <= 99999) return 5
  return null
}

/** وتحت البادئة 979: الثامنُ خانةٌ واحدة، و١٠-١٥ خانتان */
function groupLength979(body: string): number | null {
  if (!body.length) return null
  if (body[0] === '8') return 1
  if (body.length < 2) return null
  const n = Number(body.slice(0, 2))
  return n >= 10 && n <= 15 ? 2 : null
}

